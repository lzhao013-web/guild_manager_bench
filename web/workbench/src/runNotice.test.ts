import { expect, it } from "vitest";
import { runNotice } from "./runNotice";

it("不再展示比较限制和重复的曲线空状态提示", () => {
    for (const message of [null, undefined, "", "跨版本执行：历史与当前规则不完全一致，不作同版本标准比较",
        "尚未生成回放存档，等待首个可读取的结算记录", "该 run 未生成回放存档，无法提取曲线"])
        expect(runNotice(message)).toBeNull();
});

it("移除比较声明时保留同一响应中的读取失败，说明当前显示的是旧数据", () => {
    expect(runNotice("跨版本执行：历史与当前规则不完全一致，不作同版本标准比较。当前回放暂不可读或格式不符，保留上次成功读取的曲线"))
        .toBe("曲线更新失败，暂时显示上次的数据");
});

it("操作记录不完整和保存失败仍明确提示，保留服务端返回的其它错误", () => {
    expect(runNotice("整局归档轨迹尚不可用，目前只覆盖当前运行阶段，不能据此断言此前未购买或制作。最近检查点保存失败，已记录操作可能未进入恢复点，续跑时以恢复位置为准。"))
        .toBe("暂时只能查看本次启动后的操作。进度保存失败，续跑时可能丢失最近的操作");
    expect(runNotice("最近存档写入失败，曲线可能落后于运行状态")).toBe("进度保存失败，曲线可能还没更新");
    expect(runNotice("磁盘空间不足")).toBe("磁盘空间不足");
});
